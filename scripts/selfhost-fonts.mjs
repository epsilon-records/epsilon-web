#!/usr/bin/env node
// One-off: vendor the IBM Plex woff2 subsets the site actually uses (latin,
// latin-ext) into public/fonts/ and emit public/fonts.css. Re-run when the
// family changes faces or weights; the output is committed, the script is the
// provenance record.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'public', 'fonts');
mkdirSync(OUT, { recursive: true });
const css = readFileSync(join(OUT, 'gf.css'), 'utf8');

// gf.css is the css2 response for the family and weights the site declares,
// fetched with a modern Chrome UA so Google serves woff2. It is a scratch file,
// deleted after the run; the committed provenance is this script plus the
// source line in fonts.css.
const parsed = [];
const re = /\/\* ([a-z-]+) \*\/\s*@font-face\s*{([^}]+)}/g;
let m;
while ((m = re.exec(css))) {
  const body = m[2];
  parsed.push({
    subset: m[1],
    family: body.match(/font-family:\s*'([^']+)'/)?.[1],
    weight: body.match(/font-weight:\s*(\d+)/)?.[1],
    url: body.match(/url\((https:[^)]+)\)/)?.[1],
    range: body.match(/unicode-range:\s*([^;]+);/)?.[1].trim(),
  });
}

const keep = parsed.filter((f) => (f.subset === 'latin' || f.subset === 'latin-ext'));
const seen = new Set();
const faces = [];
for (const f of keep) {
  const slug = f.family.toLowerCase().replace(/\s+/g, '-') + '-' + f.weight + '-' + f.subset + '.woff2';
  if (!seen.has(slug)) {
    seen.add(slug);
    const res = await fetch(f.url);
    if (!res.ok) throw new Error('fetch failed ' + f.url);
    writeFileSync(join(OUT, slug), Buffer.from(await res.arrayBuffer()));
  }
  faces.push(`@font-face {
  font-family: "${f.family}";
  font-style: normal;
  font-weight: ${f.weight};
  font-display: swap;
  src: url("/fonts/${f.family.toLowerCase().replace(/\s+/g, '-')}-${f.weight}-${f.subset}.woff2") format("woff2");
  unicode-range: ${f.range};
}`);
}
writeFileSync(join(ROOT, 'public', 'fonts.css'), `/* IBM Plex, self-hosted latin and latin-ext subsets (SIL Open Font License 1.1,
 * see fonts/LICENSE.txt). Generated by scripts/selfhost-fonts.mjs; edit there, not here. */
${faces.join('\n')}
`);
console.log('faces:', faces.length, 'files:', seen.size);
